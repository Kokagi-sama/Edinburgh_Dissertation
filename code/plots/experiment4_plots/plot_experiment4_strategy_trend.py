"""
plot_experiment4_strategy_trend.py
----------------------------------
Generates the aggregate perturbation strategy trend plot for Experiment 4 
(Linguistic Perturbation Strategies).

This script processes the raw JSON outputs generated by `run.py` to produce the 
aggregate trend figure for Experiment 4 (Figure 7.4 in the thesis). It plots the 
mean AUROC and PR-AUC across all detectors for each perturbation strategy, 
including a shaded band representing the min-to-max spread across detectors. 
This visualises the V-shaped relationship between linguistic structure and 
detection efficacy, demonstrating that statistical disruption suffices and 
semantic coherence is not required.

The script handles both the refactored argument names (`detector_name`) 
and the legacy argument names (`scoring_model_name`) found in older `args.json` files.
"""

import os
import json
import numpy as np
import matplotlib.pyplot as plt

# Root directory containing the raw JSON outputs for Experiment 4
RESULTS_ROOT = "../../results/experiment4"

# Output directory for the generated figures
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "figures", "Experiment4")
os.makedirs(OUT_DIR, exist_ok=True)

# Maps HuggingFace detector paths to clean display names
DET_MAP = {
    'EleutherAI/pythia-1.4b': 'Pythia-1.4B',
    'EleutherAI/pythia-410m': 'Pythia-410M',
    'EleutherAI/pythia-70m': 'Pythia-70M',
}

# Maps directory names to clean display names for the perturbation strategies
TREAT_MAP = {
    '1_control_t5': 'T5 (control)',
    '2_treatment_a_synonyms': 'Synonyms',
    '3_treatment_b_random_words': 'Random words',
    '4_treatment_c_random_tokens': 'Random tokens',
}

# Exact ordering for the x-axis, spanning from full semantic coherence to pure token noise
ORDER = ['T5 (control)', 'Synonyms', 'Random words', 'Random tokens']

def extract():
    """
    Scans the results directory, extracts metrics from JSON files, and returns 
    a list of tuples containing (detector, treatment, roc_auc, pr_auc).
    
    Handles both the refactored argument names (`detector_name`) 
    and the legacy argument names (`scoring_model_name`) to ensure 
    backwards compatibility with older experiment runs.
    
    Returns:
        list: A list of tuples (str, str, float, float) representing the extracted data.
    """
    rows = []
    print(f"Scanning directories in '{RESULTS_ROOT}' for Experiment 4 results...")
    
    for root, dirs, files in os.walk(RESULTS_ROOT):
        path_parts = root.replace('\\', '/').split('/')
        treat = next((TREAT_MAP[p] for p in path_parts if p in TREAT_MAP), None)
        if treat is None:
            continue
            
        if "args.json" in files and "perturbation_50_d_results.json" in files:
            try:
                args_path = os.path.join(root, "args.json")
                results_path = os.path.join(root, "perturbation_50_d_results.json")
                
                with open(args_path, "r") as f:
                    a = json.load(f)
                with open(results_path, "r") as f:
                    r = json.load(f)
                    
                # Fallback to legacy argument names for older runs
                det_raw = a.get("detector_name") or a.get("scoring_model_name")
                det = DET_MAP.get(det_raw)
                
                roc = r.get("metrics", {}).get("roc_auc")
                pr = r.get("pr_metrics", {}).get("pr_auc")
                
                if det and (roc is not None or pr is not None):
                    rows.append((det, treat, roc, pr))
                    
            except Exception as e:
                print(f"Error parsing folder {root}: {e}")
                
    if not rows:
        print("No valid Experiment 4 results found. Check your RESULTS_ROOT path.")
    else:
        print(f"Successfully collected {len(rows)} Experiment 4 experiment runs!")
        
    return rows

def plot(rows):
    """
    Generates and saves the aggregate trend plot showing mean AUROC and PR-AUC 
    across all detectors for each perturbation strategy, with a min-max shaded band.
    
    Args:
        rows (list): The extracted experiment data from the `extract()` function.
    """
    if not rows:
        print("No data available for plotting.")
        return

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.5), sharey=True)
    
    for ax, idx, title in [(axes[0], 2, 'AUROC'), (axes[1], 3, 'PR-AUC')]:
        means, lows, highs = [], [], []
        for t in ORDER:
            vals = [row[idx] for row in rows if row[1] == t and row[idx] is not None]
            if vals:
                means.append(np.mean(vals))
                lows.append(min(vals))
                highs.append(max(vals))
            else:
                means.append(np.nan)
                lows.append(np.nan)
                highs.append(np.nan)
                
        x = np.arange(len(ORDER))
        ax.plot(x, means, marker='o', linewidth=2.5, markersize=9, color='#0072B2', label='Mean over detectors')
        ax.fill_between(x, lows, highs, color='#0072B2', alpha=0.15, label='Min to max over detectors')
        ax.axhline(0.5, color='black', linestyle='--', linewidth=1.5, label='Chance Level (0.5)')
        
        ax.set_xticks(x)
        ax.set_xticklabels(ORDER)
        ax.set_xlabel('Perturbation Strategy')
        ax.set_title(f'{title} by Perturbation Strategy')
        ax.set_ylim(0.0, 1.05)
        ax.grid(True, which='both', ls='--', alpha=0.5)
        
    axes[0].set_ylabel('Score')
    axes[0].legend(loc='lower left', fontsize=9)
    axes[1].legend(loc='lower left', fontsize=9)
    
    fig.suptitle('Detection Performance vs. Perturbation Strategy', fontsize=16)
    fig.tight_layout()
    
    out_png = os.path.join(OUT_DIR, 'exp4_strategy_trend.png')
    fig.savefig(out_png, dpi=300, bbox_inches='tight')
    print(f'Saved: {out_png}')
    plt.close(fig)

def main():
    """Orchestrates the extraction of JSON results and the generation of the trend plot."""
    # Set up global plot styling for consistent, readable figures
    plt.rcParams.update({
        'font.size': 12,
        'axes.labelsize': 14,
        'axes.titlesize': 16,
        'legend.fontsize': 11,
        'xtick.labelsize': 11,
        'ytick.labelsize': 12,
    })

    rows = extract()
    plot(rows)
    
    print("\nPlotting tasks completed successfully!")

if __name__ == '__main__':
    main()