"""
plot_experiment2_checkpoint_trends.py
-------------------------------------
Generates the aggregate checkpoint trend plots for Experiment 2 
(Training Checkpoint Dynamics).

This script reads the CSV pivot matrices generated by `plot_experiment2_heatmaps.py` 
and plots the mean AUROC and PR-AUC across all generators as a function of the 
detector's training step (Figure 5.3 in the thesis). This visualises the inverse 
relationship between training duration and detection efficacy, highlighting the 
optimal early-stopping window before overfitting degrades the likelihood surface.
"""

import os
import pandas as pd
import matplotlib.pyplot as plt

# The three Pythia detector scales evaluated in Experiment 2, ordered largest to smallest.
DET_ORDER = ['Pythia-1.4B', 'Pythia-410M', 'Pythia-70M']

# The six training checkpoints (in thousands of steps) extracted from the Pythia suite.
STEPS = [1, 5, 10, 50, 100, 143]

# Colorblind-friendly palette mapped to each detector scale for consistent plotting.
COLORS = {
    'Pythia-1.4B': '#0072B2', 
    'Pythia-410M': '#D55E00', 
    'Pythia-70M': '#009E73'
}

def load_detector_means(csv_path):
    """
    Parses a metric CSV matrix and computes the mean score across all generators 
    for each detector at each training step.
    
    Args:
        csv_path (str): Path to the CSV file containing the pivot matrix 
                        (rows = generators, columns = detector_step).
                        
    Returns:
        dict: A dictionary mapping each detector name to a list of mean scores 
              corresponding to the chronological order of STEPS.
    """
    df = pd.read_csv(csv_path, index_col=0)
    means = {}
    
    for det in DET_ORDER:
        # Identify columns matching the detector and step format (e.g., "Pythia-1.4B_1k")
        cols = [f"{det}_{s}k" for s in STEPS if f"{det}_{s}k" in df.columns]
        
        # Compute the mean across all generators (rows) for each step
        means[det] = [df[c].mean() for c in cols]
        
    return means

def plot_trend(auroc_csv, prauc_csv, out_png):
    """
    Generates and saves side-by-side line plots for AUROC and PR-AUC 
    against the detector's training step on a logarithmic x-axis.
    
    Args:
        auroc_csv (str): Path to the AUROC CSV matrix.
        prauc_csv (str): Path to the PR-AUC CSV matrix.
        out_png (str): Output filepath for the saved PNG image.
    """
    auroc = load_detector_means(auroc_csv)
    prauc = load_detector_means(prauc_csv)
    
    fig, axes = plt.subplots(1, 2, figsize=(14, 5.5), sharey=True)
    
    for ax, data, title in [(axes[0], auroc, 'AUROC'), (axes[1], prauc, 'PR-AUC')]:
        for det in DET_ORDER:
            ax.plot(STEPS, data[det], marker='o', linewidth=2.5, markersize=8,
                    color=COLORS[det], label=det)
                    
        ax.axhline(0.5, color='black', linestyle='--', linewidth=1.5, label='Chance Level (0.5)')
        ax.set_xscale('log')
        ax.set_xlabel('Training Step')
        ax.set_title(f'{title} by Training Step')
        ax.set_ylim(0.0, 1.05)
        ax.set_xticks(STEPS)
        ax.set_xticklabels([f'{s}k' for s in STEPS])
        ax.grid(True, which='both', ls='--', alpha=0.5)
        
    axes[0].set_ylabel('Mean Score')
    axes[0].legend(loc='lower left')
    axes[1].legend(loc='lower left')
    
    fig.suptitle('Detection Performance vs. Detector Training Step', fontsize=16)
    fig.tight_layout()
    fig.savefig(out_png, dpi=300, bbox_inches='tight')
    print(f'Saved: {out_png}')
    plt.close()

def main():
    """Orchestrates the generation of the checkpoint trend plots."""
    # Set up global plot styling for consistent, readable figures
    plt.rcParams.update({
        'font.size': 12,
        'axes.labelsize': 14,
        'axes.titlesize': 16,
        'legend.fontsize': 12,
        'xtick.labelsize': 12,
        'ytick.labelsize': 12,
    })

    os.makedirs('figures/Experiment2', exist_ok=True)
    
    plot_trend(
        'stepsizes_heatmap_roc_auc_matrix.csv',
        'stepsizes_heatmap_pr_auc_matrix.csv',
        'figures/Experiment2/checkpoint_trend.png'
    )
    
    print("\nPlotting tasks completed successfully!")

if __name__ == '__main__':
    main()