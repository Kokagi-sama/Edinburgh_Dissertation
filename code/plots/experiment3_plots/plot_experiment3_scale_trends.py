"""
plot_experiment3_scale_trends.py
--------------------------------
Generates the aggregate mask-filler capacity trend plots for Experiment 3 
(Semantic Perturbation Scale).

This script processes the raw JSON outputs generated by `run.py` to produce the 
scale trend figure for Experiment 3 (Figure 6.3 in the thesis). It plots the mean 
AUROC and PR-AUC across generators as a function of the mask-filling model's 
parameter count (T5-small, T5-large, T5-3B) on a logarithmic scale, highlighting 
the diminishing returns of massive mask-fillers and the interaction with detector scale.

The script handles both the refactored argument names (`mask_filler_name`, `detector_name`) 
and the legacy argument names (`mask_filling_model_name`, `scoring_model_name`) 
found in older `args.json` files.
"""

import os
import json
import matplotlib.pyplot as plt

# Root directory containing the raw JSON outputs for Experiment 3
RESULTS_ROOT = "../../results/experiment3"

# Maps HuggingFace detector paths to clean display names
DET_MAP = {
    'EleutherAI/pythia-1.4b': 'Pythia-1.4B',
    'EleutherAI/pythia-410m': 'Pythia-410M',
    'EleutherAI/pythia-70m': 'Pythia-70M',
}

# Approximate parameter counts (in millions) for the T5 mask-filling models.
# Used to map model names to their scale for the x-axis of the trend plots.
T5_MAP = {
    't5-small': 60, 
    't5-large': 770, 
    't5-3b': 3000
}

# Capacity order for the x-axis
T5_ORDER = ['t5-small', 't5-large', 't5-3b']

# Colorblind-friendly palette mapped to each detector scale for consistent plotting.
COLORS = {
    'Pythia-1.4B': '#0072B2', 
    'Pythia-410M': '#D55E00', 
    'Pythia-70M': '#009E73'
}

def extract():
    """
    Scans the results directory, extracts metrics from JSON files, and returns 
    a list of tuples containing (detector, mask_filler, roc_auc, pr_auc).
    
    Handles both the refactored argument names (`mask_filler_name`, `detector_name`) 
    and the legacy argument names (`mask_filling_model_name`, `scoring_model_name`) 
    to ensure backwards compatibility with older experiment runs.
    
    Returns:
        list: A list of tuples (str, str, float, float) representing the extracted data.
    """
    rows = []
    print(f"Scanning directories in '{RESULTS_ROOT}' for Experiment 3 results...")
    
    for root, dirs, files in os.walk(RESULTS_ROOT):
        if "args.json" in files and "perturbation_50_d_results.json" in files:
            try:
                args_path = os.path.join(root, "args.json")
                results_path = os.path.join(root, "perturbation_50_d_results.json")
                
                with open(args_path, "r") as f:
                    a = json.load(f)
                with open(results_path, "r") as f:
                    r = json.load(f)
                
                # Fallback to legacy argument names for older runs
                mask = a.get("mask_filler_name") or a.get("mask_filling_model_name")
                det_raw = a.get("detector_name") or a.get("scoring_model_name")
                det = DET_MAP.get(det_raw)
                
                roc = r.get("metrics", {}).get("roc_auc")
                pr = r.get("pr_metrics", {}).get("pr_auc")
                
                if mask in T5_MAP and det and (roc is not None or pr is not None):
                    rows.append((det, mask, roc, pr))
                    
            except Exception as e:
                print(f"Error parsing folder {root}: {e}")
                
    if not rows:
        print("No valid Experiment 3 results found. Check your RESULTS_ROOT path.")
    else:
        print(f"Successfully collected {len(rows)} Experiment 3 experiment runs!")
        
    return rows

def plot(rows):
    """
    Generates and saves side-by-side line plots for AUROC and PR-AUC 
    against the mask-filler's parameter count on a logarithmic x-axis.
    
    Args:
        rows (list): The extracted experiment data from the `extract()` function.
    """
    if not rows:
        print("No data available for plotting.")
        return

    fig, axes = plt.subplots(1, 2, figsize=(14, 5.5), sharey=True)
    
    for ax, idx, title in [(axes[0], 2, 'AUROC'), (axes[1], 3, 'PR-AUC')]:
        for det in ['Pythia-1.4B', 'Pythia-410M', 'Pythia-70M']:
            xs, ys = [], []
            for t5 in T5_ORDER:
                # Filter rows for the specific detector and mask-filler, ignoring None values
                vals = [row[idx] for row in rows if row[0] == det and row[1] == t5 and row[idx] is not None]
                if vals:
                    xs.append(T5_MAP[t5])
                    ys.append(sum(vals) / len(vals))
                    
            if xs:
                ax.plot(xs, ys, marker='o', linewidth=2.5, markersize=8, color=COLORS[det], label=det)
                
        ax.axhline(0.5, color='black', linestyle='--', linewidth=1.5, label='Chance Level (0.5)')
        ax.set_xscale('log')
        ax.set_xlabel('Mask-Filler Parameter Count')
        ax.set_title(f'{title} by Mask-Filler Capacity')
        ax.set_ylim(0.0, 1.05)
        
        # Explicitly label the T5 models with their parameter counts for readability
        ax.set_xticks([60, 770, 3000])
        ax.set_xticklabels(['T5-small\n(60M)', 'T5-large\n(770M)', 'T5-3B\n(3B)'])
        ax.grid(True, which='both', ls='--', alpha=0.5)
        
    axes[0].set_ylabel('Mean Score')
    axes[0].legend(loc='lower right')
    axes[1].legend(loc='lower right')
    
    fig.suptitle('Detection Performance vs. Mask-Filling Model Capacity', fontsize=16)
    fig.tight_layout()
    
    out_png = 'figures/Experiment3/perturbation_scale_trend.png'
    fig.savefig(out_png, dpi=300, bbox_inches='tight')
    print(f'Saved: {out_png}')
    plt.close()

def main():
    """Orchestrates the extraction of JSON results and the generation of scale trend plots."""
    # Set up global plot styling for consistent, readable figures
    plt.rcParams.update({
        'font.size': 12,
        'axes.labelsize': 14,
        'axes.titlesize': 16,
        'legend.fontsize': 12,
        'xtick.labelsize': 12,
        'ytick.labelsize': 12,
    })

    os.makedirs('figures/Experiment3', exist_ok=True)
    rows = extract()
    plot(rows)
    
    print("\nPlotting tasks completed successfully!")

if __name__ == '__main__':
    main()